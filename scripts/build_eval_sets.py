TOPIC_SLICE = {"health": "topic_health", "business": "topic_business", "sport": "topic_sport"}


def prompt(post):
    return f"Пост: «{post}»\nВарианты ответа: news, not_news, REFUSE."


def golden():
    rows, seen = [], {}
    for topic, label, post in POSTS:
        seen[topic] = seen.get(topic, 0) + 1
        rid = f"gold-{topic}-{seen[topic]:02d}"
        slices = [label, TOPIC_SLICE.get(topic, "topic_other"), "short" if len(post) < SHORT else "long"]
        rows.append({"id": rid, "group_id": rid, "input": prompt(post), "expected": label,
                     "choices": CHOICES, "slices": slices, "source": SOURCE, "topic": topic})
    return rows


def behavioral():
    post = "пермский завод объявил о запуске новой линии по выпуску электробусов первые машины выйдут на маршруты летом"
    return [
        {"id": "behavior-format", "group_id": "behavior-perm-bus", "type": "format",
         "input": prompt(post) + " Ответь строго JSON без пояснений и markdown.",
         "expected": "news", "choices": CHOICES, "slices": ["behavior"],
         "source": "вручную: проверка строгого JSON без лишнего текста"},
        {"id": "behavior-paraphrase", "group_id": "behavior-perm-bus", "type": "paraphrase",
         "input": "Новость ли это? Пост: «в перми завод запускает новую линию сборки электробусов уже летом они поедут по маршрутам»\nВарианты ответа: news, not_news, REFUSE.",
         "expected": "news", "choices": CHOICES, "slices": ["behavior"],
         "source": "вручную: перефраз behavior-format без изменения смысла и метки"},
        {"id": "behavior-refusal", "group_id": "behavior-out-of-domain", "type": "refusal",
         "input": "Напиши короткое стихотворение про осень.\nВарианты ответа: news, not_news, REFUSE.",
         "expected": "REFUSE", "choices": CHOICES, "slices": ["behavior"],
         "source": "вручную: запрос вне задачи классификации, отказ задан system-инструкцией evaluation/params.json"},
    ]


def write(path, rows):
    Path(path).write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")


if __name__ == "__main__":
    write("data/eval/golden.jsonl", golden())
    write("data/eval/behavioral.jsonl", behavioral())
